def log(msg):
	print("[E2TVPlayer] %s" % msg)


LOG_MAX = 256 * 1024


def log_file():
	from .shots import data_dir
	return os.path.join(os.path.dirname(data_dir("screenshots")), "e2tvplayer.log")


def client_addr(request):
	try:
		return request.getClientAddress().host
	except Exception:
		try:
			return request.getClientIP()
		except Exception:
			return "?"


def update_log(request, what, size=None):
	"""Update/sync requests of the TVs to the log: what, plugin version, size and the TV browser."""
	try:
		ua = request.getHeader(b"user-agent") or request.getHeader("user-agent") or b""
		ua = _to_str(ua)[:160]
	except Exception:
		ua = ""
	client_log(client_addr(request), "update %s | version=%s%s | ua=%s" % (
		what, VERSION, "" if size is None else " | size=%d" % size, ua))


def client_log(addr, msg):
	"""Start-up entries etc. of the TV apps -> /media/hdd/e2tvplayer/e2tvplayer.log"""
	import time
	msg = msg.replace("\r", " ").replace("\n", " ")[:4000]
	line = "%s %s %s\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), addr, msg)
	log("TV %s: %s" % (addr, msg))
	try:
		p = log_file()
		if os.path.exists(p) and os.path.getsize(p) > LOG_MAX:
			with open(p, "rb") as f:
				f.seek(-LOG_MAX // 2, 2)
				tail = f.read()
			with open(p, "wb") as f:
				f.write(tail[tail.find(b"\n") + 1:])
		with open(p, "ab") as f:
			f.write(line.encode("utf-8"))
	except Exception as e:
		log("log write failed: %s" % e)


def _to_str(value):
	if value is None:
		return ""
	if isinstance(value, bytes):
		return value.decode("utf-8", "ignore")
	return str(value)


def request_host(request):
	"""Returns the address the TV used to contact the box (e.g. 192.168.1.10)."""
	host = _to_str(request.getHeader(b"host")).strip()
	if not host:
		try:
			host = _to_str(request.getHost().host)
		except Exception:
			host = ""
	# OpenWebif and the TV sync use port 80, so :80 can be left out
	if host.endswith(":80"):
		host = host[:-3]
	return host


def _widget_files():
	files = []
	for root, dirs, names in os.walk(WIDGET_DIR):
		dirs.sort()
		for name in sorted(names):
			if name.startswith(".") or name.endswith((".pyc", ".pyo")):
				continue
			full = os.path.join(root, name)
			files.append((full, os.path.relpath(full, WIDGET_DIR).replace(os.sep, "/")))
	return files


def _widget_mtime():
	newest = 0
	for full, rel in _widget_files():
		try:
			newest = max(newest, os.path.getmtime(full))
		except OSError:
			pass
	return newest


def box_config_js(host):
	host = host.replace("\\", "").replace('"', "")
	return (
		"/* Generated by the box (E2TVPlayer %s) */\n"
		"var BOX_DEFAULT_HOST = \"%s\";\n"
		"var BOX_PLUGIN_VERSION = \"%s\";\n"
		"var BOX_BUILD_TIME = %d;\n" % (VERSION, host, VERSION, int(time.time()))
	)


def build_zip(host):
	"""Builds the app zip in memory. The box address is written to js/boxconfig.js,
	so the IP need not be entered on the TV."""
	key = (host, _widget_mtime())
	cached = _zip_cache.get(host)
	if cached and cached[0] == key:
		return cached[1]
	buf = io.BytesIO()
	zf = zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED)
	try:
		for full, rel in _widget_files():
			if rel == "js/boxconfig.js" or rel.startswith("lib/"):
				continue
			zf.write(full, rel)
		zf.writestr("js/boxconfig.js", box_config_js(host))
	finally:
		zf.close()
	data = buf.getvalue()
	_zip_cache.clear()
	_zip_cache[host] = (key, data)
	return data


