"""Language test apps for the old Samsung (Orsay) TVs.

Samsung never documented how a user app reads the TV menu language, and the Orsay installer
silently drops an app whose files mention a plugin it does not allow. So the experiments live
in two small separate apps that User App Sync installs next to E2TVPlayer: if the TV rejects
one of them, E2TVPlayer itself is not affected.

  E2LangTestA: NNAVI, TVMW and API plugins, the Common API objects and curWidget
  E2LangTestB: TV and SEF plugins

Each app waits for onload and sendReadyEvent, probes every candidate method immediately,
after 1 s and after 5 s, shows the results on the screen and writes them to the box log.
Results on a UE40H6275: the TV plugin GetLanguage follows the menu language (10 = Finnish,
17 = English, 25 = Swedish), which E2TVPlayer now uses. The test apps are off by default:
http://<box>/e2tvplayer/langtest?on=1 turns them on (then User App Sync).
http://<box>/e2tvplayer/langtest?tv=0 stops E2TVPlayer from using the TV plugin.
"""
from __future__ import absolute_import

import io
import os
import zipfile

VARIANTS = {
	"A": {
		"objects": [("pluginObjectNNavi", "NNAVI"), ("pluginObjectTVMW", "TVMW"), ("pluginObjectAPI", "API")],
		"sef": False,
	},
	"B": {
		"objects": [("pluginObjectTV", "TV"), ("pluginSef", "SEF")],
		"sef": True,
	},
}
METHODS = ["GetLanguage", "GetMenuLanguage", "GetSystemLanguage", "GetOSDLanguage", "GetCountry",
	"GetRegion", "GetLocale", "GetFirmware", "GetProductCode", "GetModelCode", "getLanguage"]
SEF_MODULES = ["TV", "TVMW", "NNAVI", "APPCOMMON"]
SEF_COMMANDS = ["GetLanguage", "GetMenuLanguage", "GetCountry"]


def _flag(name):
	from .shots import data_dir
	return os.path.join(os.path.dirname(data_dir("screenshots")), name)


def _set(name, present):
	p = _flag(name)
	if present:
		open(p, "w").close()
	elif os.path.exists(p):
		os.remove(p)


def enabled():
	"""the test apps are installed by User App Sync (off by default)"""
	try:
		return os.path.exists(_flag("langtest.on"))
	except Exception:
		return False


def set_enabled(on):
	_set("langtest.on", on)


def tv_language():
	"""E2TVPlayer reads the language from the Orsay TV plugin (on by default)"""
	try:
		return not os.path.exists(_flag("tvlang.off"))
	except Exception:
		return True


def set_tv_language(on):
	_set("tvlang.off", not on)


def app_id(v):
	return "E2LangTest" + v


def config_xml(main_config, v, version):
	s = main_config
	s = s.replace("<cpname>E2TVPlayer</cpname>", "<cpname>%s</cpname>" % app_id(v))
	s = s.replace("<widgetname>E2TVPlayer</widgetname>", "<widgetname>E2 Lang Test %s</widgetname>" % v)
	s = s.replace("<movie>y</movie>", "<movie>n</movie>")
	import re
	s = re.sub(r"<ver>[^<]*</ver>", "<ver>%s</ver>" % version, s)
	s = re.sub(r"<description>[^<]*</description>", "<description>E2TVPlayer language test %s</description>" % v, s)
	return s


def index_html(v):
	objs = "".join(
		'\t<object id="%s" border="0" classid="clsid:SAMSUNG-INFOLINK-%s" '
		'style="opacity:0;width:0px;height:0px;position:absolute;left:0;top:0;"></object>\n' % (i, c)
		for i, c in VARIANTS[v]["objects"])
	return (
		'<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0 Transitional//EN" "http://www.w3.org/TR/xhtml1/DTD/xhtml1-transitional.dtd">\n'
		'<html>\n<head>\n\t<meta http-equiv="Content-Type" content="text/html; charset=utf-8" />\n'
		'\t<title>E2 Lang Test %s</title>\n'
		'\t<script type="text/javascript" src="$MANAGER_WIDGET/Common/API/Widget.js"></script>\n'
		'\t<script type="text/javascript" src="$MANAGER_WIDGET/Common/API/TVKeyValue.js"></script>\n'
		'\t<script type="text/javascript" src="$MANAGER_WIDGET/Common/API/Plugin.js"></script>\n'
		'\t<script type="text/javascript" src="main.js"></script>\n'
		'</head>\n'
		'<body onload="LT.onLoad();" style="background:#0d1117;color:#e6edf3;font-family:sans-serif;margin:0;width:1280px;height:720px;overflow:hidden">\n'
		'%s'
		'\t<a href="javascript:void(0);" id="anchor" onkeydown="LT.onKey();"></a>\n'
		'\t<div style="position:absolute;left:40px;top:24px;font-size:28px">E2TVPlayer language test %s'
		' &nbsp; <span style="font-size:18px;color:#8b949e">RETURN/EXIT = close</span></div>\n'
		'\t<pre id="out" style="position:absolute;left:40px;top:80px;width:1200px;height:620px;margin:0;'
		'font-size:15px;line-height:19px;white-space:pre-wrap;overflow:hidden"></pre>\n'
		'</body>\n</html>\n'
	) % (v, objs, v)


def main_js(v, host, version):
	ids = [i for i, c in VARIANTS[v]["objects"] if c != "SEF"]
	return u"""/* E2TVPlayer language test %(v)s (generated by the box %(version)s). ES5 only. */
var LT = {
	host: '%(host)s',
	ids: %(ids)s,
	methods: %(methods)s,
	sefModules: %(sefm)s,
	sefCommands: %(sefc)s,
	useSef: %(sef)s,
	lines: [],
	widgetAPI: null,
	call: function (o, fn, args) {
		try {
			if (!o) { return 'noobj'; }
			if (typeof o[fn] === 'undefined') { return 'undef'; }
			var v = o[fn].apply(o, args || []);
			if (v === null || v === undefined) { return 'null'; }
			return String(v);
		} catch (e) { return 'err:' + String(e && e.message ? e.message : e).substring(0, 30); }
	},
	/* only the methods that give something, plus a count of the missing ones */
	probeObj: function (name, o) {
		var got = [], miss = 0;
		for (var i = 0; i < LT.methods.length; i++) {
			var r = LT.call(o, LT.methods[i]);
			if (r === 'undef' || r === 'noobj') { miss++; } else { got.push(LT.methods[i] + '=' + r); }
		}
		if (!o) { return name + ': noobj'; }
		return name + ': ' + (got.length ? got.join(' ') : '-') + (miss ? ' (' + miss + ' undef)' : '');
	},
	probe: function (label) {
		var out = [], i;
		for (i = 0; i < LT.ids.length; i++) { out.push(LT.probeObj(LT.ids[i], document.getElementById(LT.ids[i]))); }
		if (!LT.useSef) {
			try { out.push(LT.probeObj('Common.API.Plugin', typeof Common !== 'undefined' ? new Common.API.Plugin() : null)); } catch (e1) { out.push('Common.API.Plugin: err'); }
			out.push(LT.probeObj('Common.API.Widget', LT.widgetAPI));
			out.push(LT.probeObj('curWidget', window.curWidget || null));
			try { out.push('navigator: language=' + navigator.language + ' browserLanguage=' + navigator.browserLanguage + ' userLanguage=' + navigator.userLanguage + ' systemLanguage=' + navigator.systemLanguage); } catch (e2) { }
		} else {
			var sef = document.getElementById('pluginSef');
			for (i = 0; i < LT.sefModules.length; i++) {
				var m = LT.sefModules[i], res = [];
				var op = LT.call(sef, 'Open', [m, '1.000', m]);
				for (var j = 0; j < LT.sefCommands.length; j++) { res.push(LT.sefCommands[j] + '=' + LT.call(sef, 'Execute', [LT.sefCommands[j]])); }
				LT.call(sef, 'Close');
				out.push('SEF ' + m + ': open=' + op + ' ' + res.join(' '));
			}
		}
		LT.show(label, out);
		LT.send('langtest-%(v)s ' + label + ' | ' + out.join(' | '));
	},
	show: function (label, out) {
		LT.lines.push('--- ' + label);
		for (var i = 0; i < out.length; i++) { LT.lines.push(out[i]); }
		var el = document.getElementById('out');
		if (el) { el.innerHTML = LT.lines.join('\\n').replace(/&/g, '&amp;').replace(/</g, '&lt;'); }
	},
	send: function (msg) {
		try {
			var x = new XMLHttpRequest();
			x.onreadystatechange = function () { };
			x.open('GET', 'http://' + LT.host + '/e2tvplayer/log?m=' + encodeURIComponent(msg), true);
			x.send(null);
		} catch (e) { }
	},
	onLoad: function () {
		try {
			if (typeof Common !== 'undefined' && Common.API) {
				LT.widgetAPI = new Common.API.Widget();
				LT.widgetAPI.sendReadyEvent();
			}
		} catch (e) { }
		try { document.getElementById('anchor').focus(); } catch (e2) { }
		LT.probe('onload');
		setTimeout(function () { LT.probe('1 s'); }, 1000);
		setTimeout(function () { LT.probe('5 s'); }, 5000);
	},
	onKey: function () {
		var k = window.event ? window.event.keyCode : 0;
		/* RETURN 88, EXIT 45 */
		if (k === 88 || k === 45) {
			try { window.event.preventDefault(); } catch (e0) { }
			try { if (LT.widgetAPI) { LT.widgetAPI.sendReturnEvent(); } } catch (e) { }
		}
	}
};
""" % {"v": v, "version": version, "host": host.replace("'", ""), "ids": repr(ids).replace('"', "'"),
		"methods": repr(METHODS).replace('"', "'"), "sefm": repr(SEF_MODULES).replace('"', "'"),
		"sefc": repr(SEF_COMMANDS).replace('"', "'"), "sef": "true" if VARIANTS[v]["sef"] else "false"}


def build_zip(v, host, version, widget_dir):
	buf = io.BytesIO()
	zf = zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED)
	try:
		with io.open(os.path.join(widget_dir, "config.xml"), encoding="utf-8") as f:
			main_config = f.read()
		zf.writestr("config.xml", config_xml(main_config, v, version).encode("utf-8"))
		zf.writestr("index.html", index_html(v).encode("utf-8"))
		zf.writestr("main.js", main_js(v, host, version).encode("utf-8"))
		icons = os.path.join(widget_dir, "icon")
		for name in sorted(os.listdir(icons)):
			zf.write(os.path.join(icons, name), "icon/" + name)
	finally:
		zf.close()
	return buf.getvalue()
